#!/usr/bin/env python3
"""Generates the launcher icon (option D): "NU" in Lato Black inside a thin red ring.

Writes res/drawable/ic_launcher_foreground.xml and ic_launcher_monochrome.xml.
Adaptive icon canvas is 108dp; launchers show roughly the middle 72dp.
Run from the repo root: python3 tools/gen_icon.py
"""
import math, os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.join(os.path.dirname(__file__), "..")
RES = os.path.join(ROOT, "app", "src", "main", "res")
FONT = os.path.join(RES, "font", "lato_black.ttf")

C = 54.0           # canvas center
R = 25.0           # ring radius (ring ≈ 70 % of the visible 72dp, as in the mockup)
STROKE = 3.0
ARC = 0.68         # how much of the ring is red
CAP_H = 15.0       # height of the letters in dp
TRACKING = -0.03   # em, as in the mockup

TRACK = "#FF2F2627"
RED = "#FFFF3347"
WHITE = "#FFFAFAFA"


def arc_path(frac, r, c=C):
    a = 2 * math.pi * frac
    x, y = c + r * math.sin(a), c - r * math.cos(a)
    return f"M{c:.2f},{c - r:.2f} A{r},{r} 0 {1 if frac > 0.5 else 0},1 {x:.3f},{y:.3f}"


def circle_path(r, c=C):
    return f"M{c:.2f},{c - r:.2f} A{r},{r} 0 1,1 {c:.2f},{c + r:.2f} A{r},{r} 0 1,1 {c:.2f},{c - r:.2f}"


def text_path(text):
    font = TTFont(FONT)
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    upm = font["head"].unitsPerEm
    cap = font["OS/2"].sCapHeight or 0.72 * upm
    scale = CAP_H / cap
    names = [cmap[ord(ch)] for ch in text]
    advances = [gs[n].width for n in names]
    total = sum(advances) + TRACKING * upm * (len(names) - 1)
    # Center by advance width horizontally and by cap height vertically.
    x0 = C - total * scale / 2
    baseline = C + CAP_H / 2
    pen = SVGPathPen(gs)
    x = 0.0
    for n, adv in zip(names, advances):
        # font units (y up) → canvas dp (y down)
        tp = TransformPen(pen, (scale, 0, 0, -scale, x0 + x * scale, baseline))
        gs[n].draw(tp)
        x += adv + TRACKING * upm
    return pen.getCommands()


def vector(paths):
    body = ""
    for kind, d, color in paths:
        if kind == "stroke":
            body += (f'\n    <path android:pathData="{d}" android:strokeColor="{color}"'
                     f' android:strokeWidth="{STROKE}" android:strokeLineCap="round" />')
        else:
            body += f'\n    <path android:pathData="{d}" android:fillColor="{color}" />'
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_icon.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">'
            f"{body}\n</vector>\n")


letters = text_path("NU")
fg = vector([("stroke", circle_path(R), TRACK), ("stroke", arc_path(ARC, R), RED), ("fill", letters, WHITE)])
mono = vector([("stroke", arc_path(ARC, R), "#FFFFFFFF"), ("fill", letters, "#FFFFFFFF")])
for name, xml in [("ic_launcher_foreground", fg), ("ic_launcher_monochrome", mono)]:
    with open(os.path.join(RES, "drawable", name + ".xml"), "w") as f:
        f.write(xml)
print("ok")
