#!/usr/bin/env python3
"""Generates widget drawables so the widget sends no bitmaps (widget updates are size-capped).

  ring_000..ring_100   white arc, 0-100 %, round caps; tinted at runtime (tile gauges)
  ring_track           full grey circle under the arc
  btn_ring_00..15      refresh-cooldown ring: track + lime arc for N of 15 seconds left
  pulse_00..15         LIVE dot frames: lime dot + halo growing 0->7dp and fading (2 s loop)

Run from the repo root: python3 tools/gen_drawables.py
"""
import math, os

OUT = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")
TRACK = "#FF2F2627"      # ring track on #1D1718 tiles
BTN_TRACK = "#FF2E2627"
RED = "#FFFF3347"        # NU bright red (live / cooldown)


def arc_path(frac, r, c=50.0):
    frac = max(0.0, min(1.0, frac))
    if frac >= 0.999:  # full circle as two half arcs
        return f"M{c},{c-r} A{r},{r} 0 1,1 {c},{c+r} A{r},{r} 0 1,1 {c},{c-r}"
    a = 2 * math.pi * frac
    x = c + r * math.sin(a)
    y = c - r * math.cos(a)
    large = 1 if frac > 0.5 else 0
    return f"M{c},{c-r} A{r},{r} 0 {large},1 {x:.3f},{y:.3f}"


def vector(paths, size_dp=48):
    body = "".join(
        f'\n    <path android:pathData="{d}" android:strokeColor="{col}" android:strokeWidth="{w}"'
        f' android:strokeLineCap="round" android:fillColor="#00000000" />'
        for d, col, w in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/gen_drawables.py -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
        '    android:viewportWidth="100" android:viewportHeight="100">'
        f"{body}\n</vector>\n"
    )


def write(name, text):
    with open(os.path.join(OUT, name + ".xml"), "w") as f:
        f.write(text)


# Tile gauges: stroke 10 of 100, round caps
R_TILE, W_TILE = 44.0, 10.0
write("ring_track", vector([(arc_path(1, R_TILE), TRACK, W_TILE)]))
for p in range(101):
    frac = max(p, 2) / 100  # always show a sliver
    write(f"ring_{p:03d}", vector([(arc_path(frac, R_TILE), "#FFFFFFFF", W_TILE)]))

# Refresh button ring: stroke 5 of 100 (mockup: 2.5px on 48px)
R_BTN, W_BTN = 47.0, 5.0
for s in range(16):
    paths = [(arc_path(1, R_BTN), BTN_TRACK, W_BTN)]
    if s > 0:
        paths.append((arc_path(s / 15, R_BTN), RED, W_BTN))
    write(f"btn_ring_{s:02d}", vector(paths))

# Pulse frames: 20dp box, 7dp red dot, halo spread 0->6dp over the first 70 % of 2 s, alpha .65->0
for i in range(16):
    t = i / 16
    items = []
    if t < 0.7:
        k = t / 0.7
        d = 7 + 2 * 6 * k
        a = round(255 * 0.65 * (1 - k))
        items.append((d, f"#{a:02X}FF3347"))
    items.append((7, RED))
    layers = "".join(
        f'\n    <item android:gravity="center" android:width="{d:.2f}dp" android:height="{d:.2f}dp">'
        f'\n        <shape android:shape="oval"><solid android:color="{col}" /></shape>\n    </item>'
        for d, col in items
    )
    write(
        f"pulse_{i:02d}",
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_drawables.py -->\n'
        '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <item android:width="20dp" android:height="20dp"><shape android:shape="oval"><solid android:color="#00000000" /></shape></item>'
        f"{layers}\n</layer-list>\n",
    )
print("ok")
