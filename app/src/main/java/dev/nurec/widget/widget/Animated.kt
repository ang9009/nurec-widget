package dev.nurec.widget.widget

import android.annotation.SuppressLint
import android.content.Context
import androidx.compose.ui.graphics.toArgb
import android.widget.RemoteViews
import dev.nurec.widget.R
import dev.nurec.widget.data.UiState
import dev.nurec.widget.ui.Palette
import java.time.Duration
import kotlin.math.ceil

/**
 * Widgets can't run animations, but RemoteViews' ViewFlipper auto-advances through its children
 * on its own (only while the widget is on screen). Frames are drawable resources plus tiny
 * ALPHA_8 text masks, so the widget update stays small.
 */
object Animated {

    private const val PULSE_FRAMES = 16 // x 125 ms = 2 s, matching the mockup's CSS pulse
    private const val IDLE_PAD = 20

    /** Pulsing LIVE dot (frames generated by tools/gen_drawables.py). */
    fun pulse(context: Context): RemoteViews {
        val rv = RemoteViews(context.packageName, R.layout.flipper_pulse)
        for (i in 0 until PULSE_FRAMES) {
            val f = RemoteViews(context.packageName, R.layout.pulse_frame)
            f.setImageViewResource(R.id.frame, drawable(context, "pulse_%02d".format(i)))
            rv.addView(R.id.flipper, f)
        }
        return rv
    }

    /**
     * Refresh button during cooldown: one frame per remaining second ("0:15" → "0:01") with the
     * ring draining, then the idle button. The widget is redrawn when the cooldown ends; the
     * trailing idle frames cover any delay so it never wraps back to "0:15".
     */
    fun countdown(context: Context, left: Duration, textDp: Float): RemoteViews {
        val total = UiState.COOLDOWN.seconds.toInt()
        val secs = ceil(left.toMillis() / 1000.0).toInt().coerceIn(1, total)
        val rv = RemoteViews(context.packageName, R.layout.flipper_countdown)
        for (s in secs downTo 1) {
            val f = RemoteViews(context.packageName, R.layout.countdown_frame)
            val step = (s * 15f / total).toInt().coerceIn(1, 15) // ring art has 15 steps
            f.setImageViewResource(R.id.ring, drawable(context, "btn_ring_%02d".format(step)))
            val label = Glyphs.render(context, "0:%02d".format(s), Glyphs.Face.DISPLAY_SEMIBOLD, textDp)
            f.setImageViewBitmap(R.id.label, label.bitmap)
            f.setInt(R.id.label, "setColorFilter", Palette.Muted.toArgb())
            rv.addView(R.id.flipper, f)
        }
        repeat(IDLE_PAD) { rv.addView(R.id.flipper, RemoteViews(context.packageName, R.layout.countdown_idle)) }
        return rv
    }

    /** Arc drawable for a gauge, 0–100 %. */
    fun ring(context: Context, percent: Int): Int = drawable(context, "ring_%03d".format(percent.coerceIn(0, 100)))

    @SuppressLint("DiscouragedApi") // generated, numbered resources; resource shrinking is off
    private fun drawable(context: Context, name: String): Int =
        context.resources.getIdentifier(name, "drawable", context.packageName)
}
